"""Write requirements/lock-py311.txt: every installed package pinned by version and by file hash.

pip-compile has to download multi-gigabyte wheels (torch) to resolve; this reads the versions that are already
installed and asks PyPI's JSON API only for the file hashes of those exact versions.

    .venv/bin/python scripts/make_lock.py
    pip install --require-hashes -r requirements/lock-py311.txt

The environment it describes is the one the tests were run in (Python 3.11, macOS arm64). Wheels for other
platforms are included in the hash list when PyPI has them, but a platform-specific dependency tree
(for example Linux CUDA wheels) is not described.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "requirements" / "lock-py311.txt"
SKIP = {"vid3d", "pip", "setuptools", "wheel"}


def installed() -> dict[str, str]:
    out = subprocess.run([sys.executable, "-m", "pip", "list", "--format=json", "--exclude-editable"],
                         check=True, capture_output=True, text=True).stdout
    return {p["name"]: p["version"] for p in json.loads(out) if p["name"].lower() not in SKIP}


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    # curl, not urllib: python.org builds of Python often have no CA bundle installed, curl uses the system's
    raw = subprocess.run(["curl", "-fsS", "--max-time", "30", url], check=True, capture_output=True, text=True).stdout  # noqa: S607
    data = json.loads(raw)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def main() -> None:
    lines = ["# Generated by scripts/make_lock.py. Install with: pip install --require-hashes -r requirements/lock-py311.txt"]
    for name, version in sorted(installed().items(), key=lambda kv: kv[0].lower()):
        try:
            h = hashes(name, version)
        except Exception as e:  # a package that is not on PyPI under this name/version
            print(f"skipped {name}=={version}: {e}", file=sys.stderr)
            continue
        lines.append(f"{name}=={version} \\")
        lines.extend(f"    --hash=sha256:{x} \\" for x in h[:-1])
        lines.append(f"    --hash=sha256:{h[-1]}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
